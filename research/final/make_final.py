def all_pars(doc):
    for p in doc.paragraphs: yield p
    for t in doc.tables:
        for r in t.rows:
            for c in r.cells:
                for p in c.paragraphs: yield p
def set_text(p,new):
    runs=p.runs
    runs[0].text=new
    for r in runs[1:]: r._r.getparent().remove(r._r)
log=[]
def rep(old,new,count=1):
    n=0
    for p in all_pars(d):
        if old in p.text:
            set_text(p,p.text.replace(old,new)); n+=1
    log.append((n,old[:40]))
    assert n>=1,('NOT FOUND',old[:60])
