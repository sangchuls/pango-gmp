def set_text(p,text):
    p.runs[0].text=text
    for r in p.runs[1:]: r._r.getparent().remove(r._r)
def append_text(p,text): p.runs[-1].text+=text
def new_par(after_el,text,tpl=body_tpl):
    el=copy.deepcopy(tpl); after_el.addnext(el)
    p=Paragraph(el,P[12]._parent); set_text(p,text); return el
def delete(p): p._p.getparent().remove(p._p)
def new_table(after_el,header,rows):
    tbl=copy.deepcopy(T[0]._tbl); after_el.addnext(tbl)
    trs=tbl.tr_lst; hdr,tpl=trs[0],trs[1]
    for tr in trs[2:]: tbl.remove(tr)
    def fill(tr,vals):
        for tc,v in zip(tr.tc_lst,vals):
            ps=tc.findall('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}p')
            pp=Paragraph(ps[0],P[12]._parent); set_text(pp,v)
    fill(hdr,header)
    for v in rows:
        tr=copy.deepcopy(tpl); tbl.append(tr); fill(tr,v)
    tbl.remove(tpl); return tbl

